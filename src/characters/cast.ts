export type CharacterType = 'protocol' | 'portrayal';
export type AskMode = 'explain' | 'role';
export type Scenario = 'passive' | 'active';

export interface SourceLink {
  label: string;
  url: string;
}

export interface Biography {
  fullName: string;
  contribution: string;
  topics: string[];
  sources: SourceLink[];
  /** Historical caution kept separate from quest dialogue. */
  note: string;
}

export interface Portrait {
  hair: string;
  shirt: string;
  pants: string;
  glasses?: boolean;
}

export interface Character {
  id: string;
  name: string;
  tag: string;
  type: CharacterType;
  role: string;
  specialties: string[];
  regions: string[];
  questions: string[];
  topics: string[];
  biography?: Biography;
  limits: string;
  portrait: Portrait;
}

export interface Region {
  id: string;
  name: string;
  open: boolean;
  summary: string;
  topics: string[];
}

export interface Appearance {
  id: string;
  characterId: string;
  regionId: string;
  x: number;
  y: number;
  inside: boolean;
  topic?: string;
  guest: string;
  signed: string;
  questions: string[];
  context: string;
}

